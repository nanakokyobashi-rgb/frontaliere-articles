/**
 * scan-failed-runs-family.test.mjs — le famiglie di workflow GENERATI di
 * `scripts/ci/scan-failed-runs.mjs`.
 * Run with `node --test generator/tests/scan-failed-runs-family.test.mjs`.
 *
 * Il caso misurato: il 2026-10-05 i caller cantonali generati sono falliti
 * tutti insieme per una sola causa, e lo scanner ha aperto una issue per
 * cantone — 18 aperte il 2026-10-06, tutte senza nessun job fallito. Il triage
 * le ha instradate una per una, e i fixer in parallelo hanno prodotto sei PR
 * sugli stessi 26 file.
 *
 * Lo scanner SOPPRIME una segnalazione, quindi ogni caso positivo ha accanto
 * i negativi che lo tengono stretto: firma diversa, firma illeggibile, issue
 * vecchia, workflow fuori famiglia.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  FAMILY_COVER_MAX_AGE_HOURS,
  GENERATED_WORKFLOW_FAMILIES,
  NO_FAILED_JOBS_LINE,
  RUN_LEVEL_SIGNATURE,
  failureSignature,
  failureSignatureFromIssueBody,
  familySiblingsNote,
  openSiblingIssueCovering,
  planFamilyCollapse,
  runLevelSignature,
  workflowFamilyOf,
} from '../../scripts/ci/scan-failed-runs.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const WORKFLOWS = path.resolve(HERE, '../../.github/workflows');
const NOW = Date.parse('2026-10-06T03:00:00Z');
const canton = (code) => `Generate Blog Article (canton-${code})`;
const job = (step) => ({ name: 'generate / generate', step, url: 'https://example.invalid/job' });
const SHA = 'a'.repeat(40);
const OTHER_SHA = 'b'.repeat(40);
const runLevelEntry = (code, over = {}) => ({
  name: canton(code), jobs: [], runLevel: true, event: 'push', headSha: SHA, runUrl: `https://example.invalid/run/${code}`, ...over,
});

/** Il corpo generico come lo scrive `main`, ridotto alle righe che contano. */
const issueBody = (name, jobLines, { event = 'push', sha = SHA } = {}) => [
  `Il workflow **${name}** è fallito.`,
  '',
  '- Run: https://example.invalid/run',
  '- Branch: `main`',
  `- Evento: \`${event}\``,
  ...(sha ? [`- Commit: \`${sha}\``] : []),
  '- Concluso: 2026-10-05T20:49:01Z',
  '',
  '**Job falliti**',
  jobLines,
].join('\n');
const openIssue = (code, {
  number = 2236, jobLines = NO_FAILED_JOBS_LINE, createdAt = '2026-10-05T22:37:00Z', event = 'push', sha = SHA,
} = {}) => ({
  number,
  title: `Workflow Failure: ${canton(code)}`,
  body: issueBody(canton(code), jobLines, { event, sha }),
  createdAt,
});

// ── La famiglia è legata agli YAML veri ─────────────────────────────────────

test('ogni caller generato appartiene alla famiglia, e solo quelli', () => {
  const family = GENERATED_WORKFLOW_FAMILIES.find((f) => f.id === 'canton-article');
  assert.ok(family, 'famiglia canton-article non dichiarata');
  const generated = [];
  const handWritten = [];
  for (const file of readdirSync(WORKFLOWS).filter((f) => /^generate-article.*\.yml$/.test(f))) {
    const text = readFileSync(path.join(WORKFLOWS, file), 'utf8');
    const name = /^name:\s*(.+)$/m.exec(text)?.[1].trim().replace(/^['"]|['"]$/g, '');
    assert.ok(name, `${file}: \`name:\` non trovato`);
    // Un caller è generato E chiama il core. Il core riusabile esce dallo
    // stesso generatore ma è UNO: non ha fratelli con cui collassare.
    const isCaller = text.includes(`AUTO-GENERATED by ${family.source}`)
      && /^\s+uses: \.\/\.github\/workflows\/generate-article-core\.yml$/m.test(text);
    (isCaller ? generated : handWritten).push({ file, name });
  }
  assert.ok(generated.length >= 2, `attesi i caller generati da ${family.source}, trovati ${generated.length}`);
  for (const { file, name } of generated) {
    assert.equal(workflowFamilyOf(name)?.id, 'canton-article', `${file} («${name}») è generato ma fuori dalla famiglia: una sua failure aprirebbe di nuovo una issue per caller`);
    assert.ok(`Workflow Failure: ${name}`.startsWith(family.titleSearch), `${file}: il titolo della issue non contiene la frase di ricerca della famiglia`);
  }
  for (const { file, name } of handWritten) {
    assert.equal(workflowFamilyOf(name), null, `${file} («${name}») è scritto a mano: collassarlo nasconderebbe un guasto indipendente`);
  }
});

test('i workflow fuori famiglia non vengono mai collassati', () => {
  for (const name of ['Generate Blog Article', 'tests', 'Crawler Group 01 (sparse cross-repo execution)', 'Refresh Canton Hubs', '']) {
    assert.equal(workflowFamilyOf(name), null, name);
  }
  assert.equal(workflowFamilyOf('Generate Blog Article (canton-vs) extra'), null);
});

// ── Firma ───────────────────────────────────────────────────────────────────

test('firma: step falliti ordinati e senza duplicati; vuota se non c\'è niente di leggibile', () => {
  assert.equal(failureSignature([job('Generate article'), job('Commit and push'), job('Generate article')]), 'Commit and push | Generate article');
  assert.equal(failureSignature([{ name: 'generate / generate', step: null }]), '');
  assert.equal(failureSignature([]), '', 'una lista vuota senza `runLevel` non è una firma: può essere una lettura fallita');
  // «Nessun job» da solo non è una firma: serve l'evidenza della causa
  // condivisa, cioè lo stesso evento sullo stesso commit.
  assert.equal(failureSignature([], { runLevel: true }), '');
  assert.equal(failureSignature([], { runLevel: true, event: 'push' }), '');
  assert.equal(failureSignature([], { runLevel: true, event: 'push', headSha: 'abc123' }), '', 'uno SHA abbreviato non identifica un commit');
  const signature = failureSignature([], { runLevel: true, event: 'push', headSha: SHA });
  assert.ok(signature.startsWith(RUN_LEVEL_SIGNATURE) && signature.includes(SHA) && signature.includes('push'), signature);
  assert.equal(signature, runLevelSignature({ event: 'PUSH', headSha: SHA.toUpperCase() }), 'evento e SHA si confrontano senza distinzione di maiuscole');
  assert.notEqual(signature, runLevelSignature({ event: 'push', headSha: OTHER_SHA }));
  assert.notEqual(signature, runLevelSignature({ event: 'schedule', headSha: SHA }));
});

test('firma riletta dal corpo di una issue: combacia con quella calcolata dai job', () => {
  const jobs = [job('Generate article')];
  const lines = jobs.map((j) => `- \`${j.name}\` — step fallito: \`${j.step}\`\n  ${j.url}`).join('\n');
  assert.equal(failureSignatureFromIssueBody(issueBody(canton('vs'), lines)), failureSignature(jobs));
  assert.equal(
    failureSignatureFromIssueBody(issueBody(canton('vs'), NO_FAILED_JOBS_LINE)),
    runLevelSignature({ event: 'push', headSha: SHA }),
  );
  // Le issue aperte prima di questa modifica non hanno la riga «Commit»:
  // nessuna firma, quindi non coprono nessuno.
  assert.equal(failureSignatureFromIssueBody(issueBody(canton('vs'), NO_FAILED_JOBS_LINE, { sha: '' })), '');
  // Un corpo che non è quello generico (report ricco, issue scritta a mano) non ha firma.
  assert.equal(failureSignatureFromIssueBody('**Un articolo generato per intero è stato buttato via.**'), '');
  assert.equal(failureSignatureFromIssueBody(''), '');
});

// ── Stessa passata ──────────────────────────────────────────────────────────

test('run-level su commit o eventi diversi NON si collassa: può essere un difetto del singolo caller', () => {
  const plan = planFamilyCollapse([
    runLevelEntry('vs'),
    runLevelEntry('fr', { headSha: OTHER_SHA }),
    runLevelEntry('ti', { event: 'schedule' }),
    runLevelEntry('ge', { headSha: '' }),
    runLevelEntry('lu', { headSha: undefined }),
  ]);
  assert.equal(plan.covered.size, 0, 'senza lo stesso commit e lo stesso evento non c\'è evidenza di una causa condivisa');
});

test('IL CASO 2026-10-05: N caller falliti a livello di run sullo stesso push → un rappresentante', () => {
  const codes = ['vs', 'appenzello', 'ti', 'lu', 'ge', 'fr', 'sz', 'be', 'ow', 'so'];
  const plan = planFamilyCollapse(codes.map(runLevelEntry));
  assert.equal(plan.covered.size, codes.length - 1, 'tutti i fratelli devono essere coperti dal primo');
  for (const code of codes.slice(1)) assert.equal(plan.covered.get(canton(code)), canton('vs'));
  assert.equal(plan.covered.has(canton('vs')), false, 'il rappresentante non è coperto da nessuno');
  assert.deepEqual(plan.siblings.get(canton('vs')).map((s) => s.name), codes.slice(1).map(canton));
});

test('firme diverse nella stessa famiglia restano issue separate', () => {
  const plan = planFamilyCollapse([
    { name: canton('vs'), jobs: [job('Generate article')] },
    { name: canton('fr'), jobs: [job('Commit and push')] },
    { name: canton('ti'), jobs: [job('Generate article')] },
    runLevelEntry('ge'),
  ]);
  assert.deepEqual([...plan.covered], [[canton('ti'), canton('vs')]]);
});

test('senza firma leggibile un membro non copre e non è coperto', () => {
  const plan = planFamilyCollapse([
    { name: canton('vs'), jobs: [] },
    { name: canton('fr'), jobs: [] },
    { name: canton('ti'), jobs: [{ name: 'generate / generate', step: null }] },
  ]);
  assert.equal(plan.covered.size, 0, 'liste vuote senza `runLevel` sono letture non attendibili');
});

test('un workflow fuori famiglia con la stessa firma non entra nel gruppo', () => {
  const plan = planFamilyCollapse([
    { name: 'Generate Blog Article', jobs: [job('Generate article')] },
    { name: canton('vs'), jobs: [job('Generate article')] },
    { name: 'Refresh Canton Hubs', jobs: [], runLevel: true },
    runLevelEntry('fr'),
  ]);
  assert.equal(plan.covered.size, 0);
});

// ── Passate successive: una issue già aperta ────────────────────────────────

test('una issue aperta di un fratello con la stessa firma copre il membro', () => {
  const sibling = openSiblingIssueCovering(runLevelEntry('fr'), [openIssue('vs')], { now: NOW });
  assert.equal(sibling?.number, 2236);
});

test('la issue del membro stesso non lo «copre»: decide la dedup ordinaria', () => {
  assert.equal(openSiblingIssueCovering(runLevelEntry('vs'), [openIssue('vs')], { now: NOW }), null);
});

test('firma diversa, issue vecchia, data illeggibile o titolo fuori famiglia: nessuna copertura', () => {
  const stepLines = '- `generate / generate` — step fallito: `Generate article`\n  https://example.invalid/job';
  const cover = (issue, entry = runLevelEntry('fr')) => openSiblingIssueCovering(entry, [issue], { now: NOW });
  assert.equal(cover(openIssue('vs', { jobLines: stepLines })), null, 'la issue descrive un guasto di step, questo è di livello run');
  assert.equal(cover(openIssue('vs'), { name: canton('fr'), jobs: [job('Generate article')] }), null);
  const old = new Date(NOW - (FAMILY_COVER_MAX_AGE_HOURS + 1) * 3_600_000).toISOString();
  assert.equal(cover(openIssue('vs', { createdAt: old })), null, 'una issue parcheggiata non deve coprire per sempre');
  assert.equal(cover(openIssue('vs', { createdAt: '' })), null);
  // Stesso «nessun job», ma un altro commit o nessun commit nel corpo.
  assert.equal(cover(openIssue('vs', { sha: OTHER_SHA })), null);
  assert.equal(cover(openIssue('vs', { sha: '' })), null, 'una issue senza la riga «Commit» non prova la causa condivisa');
  assert.equal(cover(openIssue('vs', { event: 'schedule' })), null);
  assert.equal(cover({ ...openIssue('vs'), title: 'Workflow Failure: Generate Blog Article' }), null);
  assert.equal(cover({ ...openIssue('vs'), title: `[crawler-goal] ${canton('vs')}` }), null);
  // Lettura dei job non riuscita: nessuna firma, quindi nessuna copertura.
  assert.equal(cover(openIssue('vs'), { name: canton('fr'), jobs: [] }), null);
  assert.equal(cover(openIssue('vs'), runLevelEntry('fr', { headSha: '' })), null);
  assert.equal(openSiblingIssueCovering(runLevelEntry('fr'), null, { now: NOW }), null);
});

// ── Il corpo della issue rappresentante ─────────────────────────────────────

test('la issue del rappresentante dice al fixer che è una classe e dove correggere', () => {
  const family = workflowFamilyOf(canton('vs'));
  const note = familySiblingsNote(family, [
    { name: canton('fr'), runUrl: 'https://example.invalid/run/fr' },
    { name: canton('ti'), runUrl: '' },
  ]);
  assert.match(note, /Stessa famiglia, stessa firma, nella stessa passata \(2\)/);
  assert.ok(note.includes(family.source), 'la nota deve nominare la sorgente dei caller generati');
  assert.match(note, /canton-fr\) — https:\/\/example\.invalid\/run\/fr/);
  assert.match(note, /- Generate Blog Article \(canton-ti\)$/m);
  assert.equal(familySiblingsNote(family, []), '');
  assert.equal(familySiblingsNote(null, [{ name: canton('fr') }]), '');
});

test('il corpo generico scrive il commit: senza, la firma non sarebbe rileggibile', () => {
  const src = readFileSync(path.resolve(HERE, '../../scripts/ci/scan-failed-runs.mjs'), 'utf8');
  assert.match(src, /\`- Commit: \\\`\$\{String\(run\.headSha\)\.toLowerCase\(\)\}\\\`\`/, 'la riga «- Commit:» deve stare nel corpo generico');
  assert.match(src, /'--json', 'databaseId,[^']*headSha[^']*'/, 'la lettura delle run deve chiedere headSha');
});

test('la riga «nessun job fallito» ha una sola sorgente', () => {
  const src = readFileSync(path.resolve(HERE, '../../scripts/ci/scan-failed-runs.mjs'), 'utf8');
  assert.equal(
    src.split('possibile fallimento a livello di run').length - 1,
    1,
    'la riga è scritta da `main` e riletta da `failureSignatureFromIssueBody`: due copie divergerebbero in silenzio',
  );
  assert.ok(src.includes(': NO_FAILED_JOBS_LINE;'), '`main` deve usare la costante condivisa');
});
