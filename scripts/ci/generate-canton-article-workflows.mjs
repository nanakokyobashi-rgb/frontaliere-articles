/**
 * Toglie le righe di solo commento e compatta le righe vuote. Dentro un heredoc
 * non tocca niente: li' una riga che comincia con `#` e' un dato, non un commento.
 *
 * @param {string} text
 * @returns {string}
 */
export function stripComments(text) {
  const out = [];
  let heredocEnd = null;
  for (const line of text.split('\n')) {
    if (heredocEnd !== null) {
      out.push(line);
      if (line.trim() === heredocEnd) heredocEnd = null;
      continue;
    }
    if (line.trim().startsWith('#')) continue;
    if (line.trim() === '' && out.length && out[out.length - 1].trim() === '') continue;
    out.push(line);
    const heredoc = /(?<!<)<<-?(?!<)\s*(['"]?)([A-Za-z_][A-Za-z0-9_]*)\1/.exec(line);
    if (heredoc) heredocEnd = heredoc[2];
  }
  if (heredocEnd !== null) throw new Error(`heredoc <<${heredocEnd} mai chiuso nella sorgente`);
  return out.join('\n');
}

