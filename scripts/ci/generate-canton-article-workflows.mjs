/** `generate-article-<codice-minuscolo>.yml`. */
export function callerWorkflowFile(code) {
  if (!/^[A-Z]+$/.test(String(code))) throw new Error(`codice cantone non valido: "${code}"`);
  return `generate-article-${String(code).toLowerCase()}.yml`;
}

/**
 * Lo sfasamento in ore di ogni cantone dentro la sua cadenza: i cantoni con la
 * stessa cadenza, in ordine di sezione, si distribuiscono in modo uniforme
 * sull'intervallo.
 *
 * @param {Array<{ section: string, cadenceHours: number }>} cantons
 * @returns {Map<string, number>}
 */
export function hourOffsets(cantons) {
  const byCadence = new Map();
  for (const c of [...cantons].sort((a, b) => a.section.localeCompare(b.section))) {
    if (!byCadence.has(c.cadenceHours)) byCadence.set(c.cadenceHours, []);
    byCadence.get(c.cadenceHours).push(c.section);
  }
  const out = new Map();
  for (const [cadence, sections] of byCadence) {
    sections.forEach((section, i) => out.set(section, Math.floor((i * cadence) / sections.length)));
  }
  return out;
}

/** L'espressione cron di un cantone. */
export function cronExpression({ cronMinute, cadenceHours }, offset) {
  if (!Number.isInteger(cronMinute) || cronMinute < 0 || cronMinute > 59) throw new Error(`cronMinute non valido: ${cronMinute}`);
  if (!Number.isInteger(cadenceHours) || cadenceHours < 1 || 24 % cadenceHours !== 0) {
    throw new Error(`cadenceHours ${cadenceHours} non divide le 24 ore`);
  }
  if (!Number.isInteger(offset) || offset < 0 || offset >= cadenceHours) throw new Error(`sfasamento ${offset} fuori da [0, ${cadenceHours})`);
  if (cadenceHours === 1) return `${cronMinute} * * * *`;
  const hours = [];
  for (let h = offset; h < 24; h += cadenceHours) hours.push(h);
  return `${cronMinute} ${hours.join(',')} * * *`;
}

const escapeRegex = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * I path del corpus che provano «la sezione ha ricevuto un articolo», piu' la
 * regex dei suoi corpi. Derivati dal core tramite `sectionWriteSurfaces`.
 *
 * @param {string} section
 */
export function sectionCorpusPaths(section) {
  const s = sectionWriteSurfaces(section);
  const sectionDir = path.posix.dirname(s.registryFile);
  for (const [name, file] of [['slugDataFile', s.slugDataFile], ['seoWriteFile', s.seoWriteFile]]) {
    if (path.posix.dirname(file) !== sectionDir) {
      throw new Error(`${section}: ${name} (${file}) non sta in ${sectionDir}/ come il registro: i push.paths non lo coprirebbero`);
    }
  }
  for (const p of [s.bodyDir, sectionDir, ...s.metaFiles]) {
    if (!p.startsWith('content/')) throw new Error(`${section}: ${p} non e' sotto content/`);
  }
  return {
    pushPaths: [`${s.bodyDir}/**`, ...s.metaFiles, `${sectionDir}/**`],
    bodyPathRegex: `^${escapeRegex(s.bodyDir)}/[a-z]{2}/.+\\.ts$`,
  };
}

