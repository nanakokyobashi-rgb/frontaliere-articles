function isMain() {
  try {
    return realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (isMain()) {
  try {
    if (process.argv.includes('--check')) {
      const problems = checkGenerated();
      if (problems.length) {
        for (const p of problems) console.error(`✖ ${p}`);
        console.error(`\nRigenera con: node ${GENERATOR_REL}`);
        process.exit(1);
      }
      console.log(`✅ ${CORE_WORKFLOW} e i chiamanti cantonali sono allineati al generatore.`);
    } else {
      const files = buildFromRepo();
      for (const [file, content] of files) writeFileSync(path.join(ROOT, WORKFLOWS_DIR, file), content);
      console.log(`✅ Scritti ${files.size} workflow (${CORE_WORKFLOW} + ${CANTON_SELF_TEST_WORKFLOW} + ${files.size - 2} chiamanti).`);
    }
  } catch (error) {
    console.error(`✖ ${error?.message ?? error}`);
    process.exit(1);
  }
}
