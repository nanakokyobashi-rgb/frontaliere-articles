function countOccurrences(haystack, needle) {
  let n = 0;
  for (let at = haystack.indexOf(needle); at !== -1; at = haystack.indexOf(needle, at + needle.length)) n += 1;
  return n;
}

/** Solo le righe eseguibili (stesso filtro dei test che leggono i workflow). */
function activeLines(text) {
  return text.split('\n').filter((l) => !l.trim().startsWith('#')).join('\n');
}

/**
 * Il core, dal testo di `generate-article.yml`.
 *
 * @param {string} source
 * @returns {string}
 */
export function buildCoreWorkflow(source) {
  const lines = source.split('\n');
  const jobsAt = lines.indexOf('jobs:');
  if (jobsAt === -1) throw new Error(`${SOURCE_WORKFLOW}: riga \`jobs:\` non trovata`);
  if (lines.lastIndexOf('jobs:') !== jobsAt) throw new Error(`${SOURCE_WORKFLOW}: piu' di una riga \`jobs:\``);
  let jobs = stripComments(lines.slice(jobsAt).join('\n'));
  for (const { id, find, replace, count } of CORE_REPLACEMENTS) {
    const seen = countOccurrences(jobs, find);
    if (seen !== count) {
      throw new Error(
        `sostituzione «${id}»: l'ancoraggio compare ${seen} volte in ${SOURCE_WORKFLOW} (attese ${count}). `
          + `La sorgente e' cambiata vicino a un punto cablato: aggiorna CORE_REPLACEMENTS in ${GENERATOR_REL}.`,
      );
    }
    jobs = jobs.split(find).join(replace);
  }
  for (const literal of CORE_FORBIDDEN_LITERALS) {
    // Il job `section_gate` e' testo di questo file, non della sorgente.
    const leftover = jobs.replace(SECTION_GATE_JOB, '').split('\n').filter((l) => l.includes(literal)
      // I messaggi di log e di errore nominano le sezioni storiche e il
      // workflow come esempi: sono testo per chi legge, non logica.
      && !/^\s*(echo |\[ -n "\$undeclared_why" \]|stop )/.test(l)
      && !/::(warning|error)::/.test(l));
    if (leftover.length) {
      throw new Error(
        `il core ha ancora «${literal}» cablato in una riga eseguibile:\n${leftover.join('\n')}\n`
          + `Aggiungi la sostituzione a CORE_REPLACEMENTS in ${GENERATOR_REL}.`,
      );
    }
  }
  return `${CORE_HEADER}${jobs.replace(/\n*$/, '')}\n`;
}

